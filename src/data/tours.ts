export function buildGoogleMapsStopUrl(query: string): string {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`;
}

export function buildGoogleMapsRouteUrl(stops: TourStop[]): string {
  if (stops.length === 0) return "https://www.google.com/maps";
  if (stops.length === 1) return buildGoogleMapsStopUrl(stops[0].googleMapsQuery);
  const origin = encodeURIComponent(stops[0].googleMapsQuery);
  const destination = encodeURIComponent(stops[stops.length - 1].googleMapsQuery);
  const middle = stops.slice(1, -1).map((s) => s.googleMapsQuery);
  const waypoints = middle.length > 0 ? `&waypoints=${encodeURIComponent(middle.join("|"))}` : "";
  return `https://www.google.com/maps/dir/?api=1&origin=${origin}&destination=${destination}${waypoints}&travelmode=driving`;
}

